import pandas as pd                  # pandas для работы с таблицами, псевдоним pd
import numpy as np                   # numpy для математики и массивов, псевдоним np
import matplotlib.pyplot as plt      # модуль pyplot из matplotlib, псевдоним plt — для рисования графиков
import seaborn as sns                # seaborn — надстройка над matplotlib для красивых статистических графиков


df = pd.read_csv('data/FiresRu.csv')                      # читаем CSV-файл в таблицу df

# 3.2. Поиск выЛинейныйо осадкам методом IQR
osadki = df['precipitation_mm']                      # берём столбец осадков
q1 = osadki.quantile(0.25)                           # 25-й перцентиль (25% значений ниже этого)
q3 = osadki.quantile(0.75)                           # 75-й перцентиль (75% значений ниже этого)
iqr = q3 - q1                                        # межквартильный размах = q3 - q1
lower = q1 - 1.5 * iqr                               # нижняя граница «нормы»
upper = q3 + 1.5 * iqr                               # верхняя граница «нормы»
outliers = df[(osadki < lower) | (osadki > upper)]   # выбросы: значения ниже нижней ИЛИ выше верхней границы (| = ИЛИ)
inner = df[(osadki > lower) & (osadki < upper)].head(3000)  # «чистые» данные (без выбросов), берём первые 3000 строк (& = И)


# 3.3. СоЛинейныйигуры 2×2
fig, ax = plt.subplots(2, 2, figsize=(12, 5), layout='constrained')  # фигура + сетка 2×2 графиков; figsize в дюймах; layout авто-выравнивает подписи
# Axes - область с осями                        # комментарий-напоминание: ax — это массив осей


# 3.4. Линейныймма температур (левый верхний)
ax[0][0].hist(df['temperature_c'], bins=30)          # гистограмма температур, 30 столбиков
ax[0][0].set_title('Распределение температур')       # заголовок
ax[0][0].set_xlabel('Температура')                   # подпись оси X
ax[0][0].set_ylabel('Частота')                       # подпись оси Y


# 3.5. ГЛинейныйма осадков без выбросов (левый нижний)
ax[1][0].hist(inner['precipitation_mm'], bins=30)    # гистограмма осадков без выбросов (inner)
ax[1][0].set_title('Распределение осадков')          # заголовок
ax[1][0].set_xlabel('мм, осадки')                    # подпись X
ax[1][0].set_ylabel('Частота')                       # подпись Y



# 3.6. ГЛинейныйма влажности (правый верхний)
ax[0][1].hist(df['relative_humidity'], bins=30)      # гистограмма относительной влажности
ax[0][1].set_title('Распределение влажности')        # заголовок
ax[0][1].set_xlabel('Влажность')                     # подпись X
ax[0][1].set_ylabel('Частота')                       # подпись Y



# 3.7. Линейныйгистограмма скорости ветра по типам пожара (правый нижний)
sns.histplot(data=df,                                # seaborn: гистограмма по данным df
             x="wind_speed_ms",                      # по X — скорость ветра
             hue="type_name",                        # разбить по цвету по типу пожара
             element='step',                         # рисовать ступеньками (контуром), а не залитыми столбцами
             stat='density',                         # по Y — плотность, а не абсолютная частота (чтобы можно было сравнивать группы)
             common_norm=False,                      # нормировать каждую группу отдельно (иначе большие группы «съедят» маленькие)
             ax=ax[1][1])                            # явно указываем, куда рисовать (в правый нижний слот сетки)
# ax[1][1].set_title('Скорость ветра по типам пожара') # заголЛинейный3.8. Сохранение фигуры
fig.savefig('output/itog.png')                              # сохраняем всю фигуру 2×2 в файл itog.png



# 3.9.Линейныйчный график
fig, _ = plt.subplots(figsize=(12, 5), layout='constrained')  # новая фигура; _ = «мне не нужен второй результат»
ax3 = fig.add_subplot(111, projection='3d')          # добавляем оси с 3D-проекцией (111 = 1 строка, 1 столбец, 1-й график)
ax3.scatter3D(xs='solar_radiation',                  # 3D-рассеивание: ось X — солнечная радиация (передаём имя столбца)
                 ys='relative_humidity',             # ось Y — влажность
                 zs='precipitation_mm',              # ось Z — осадки
                 cmap='plasma',                      # цветовая карта
                 c='type_id',                        # цвет точек — по типу пожара
                 data=inner,                         # откуда брать столбцы (только «чистые» данные)
                 alpha=0.5)                          # прозрачность 50%
ax3.set_zlabel('Осадки')                             # подпись оси Z
ax3.set_ylabel('Влажность')                          # подпись оси Y
ax3.set_xlabel('Солнечная радиация')                 # подпись оси X
plt.show()                                           # показываем 3D-график



# 3.10. Линейный график температуры и влажности
df.plot(kind='line', x='temperature_c', y='relative_humidity')  # строим линейный график; ОПЕЧАТКА: 'king' вместо 'kind' → ошибка TypeError
plt.show()                                           # показываем график


